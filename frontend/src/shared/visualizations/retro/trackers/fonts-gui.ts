/**
 * The bitmap fonts of the GUI tracker screens (ahx.ts, octamed.ts, modplug.ts), drawn for this
 * project as text in the manner of fonts.ts: each block is a line naming the characters, then
 * their rows of pixels, one cell of columns per character and a column between ('#' lit). Without
 * runtime imports, so the tests read them as they are; the scenes hand them to sheet() (raster.ts).
 *
 * Drawn by hand after screenshots of the programs, in their manner; nothing is taken from them.
 *
 * - AHX_LABEL: AHX's panel labels, 8 × 5 capitals with every upright two pixels wide (the
 *   scene sets them white over a black shadow, seven pixels apart).
 * - AHX_DATA: AHX's chunky 8 × 8 face for values, names and tracks: capitals on seven rows,
 *   the small letters and the slashed nought one row lower, a descender on the eighth.
 * - OM: OctaMED's 8 × 8 face of the panel and the editor (which draws it twice as wide for
 *   four tracks): square, two-pixel uprights, a slashed nought, capitals on seven rows. The
 *   panel sets it proportionally, the editor and the numbers in its cells.
 * - OM_WIDE: the broader capitals of TIMER and the window menu, six rows, eight pixels wide.
 * - OM_LABEL: the panel's small capitals and digits on its buttons and labels, five rows.
 * - OM_LOGO: the letters of the title strip's "OctaMED-Professional", twelve rows, proportional
 *   (the scene shades them like metal).
 * - OM_THIN: the version beside it, "(v4.00)", ten rows; OM_SMALL: the author's name, six rows.
 * - WIN: a Windows 98 dialog face in the manner of MS Sans Serif at 8 points, proportional:
 *   capitals on rows 1–8, descenders on 9–10 (ModPlug's window; the scene makes it bold too).
 * - MPT: ModPlug Tracker's thin pattern face, 4 × 9 on a pitch of 5, with the volume column's
 *   small letters set a row lower.
 */

